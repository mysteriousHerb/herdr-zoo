"""Merge the sprite packs' catalogs (mods/zoo/packs/<pack>.json) into sprites.js, which the
zoo, zoo-agents and my-tabs mods import (a mod can't import from another's folder, so each gets a copy).

Each pack's JSON: {id, name, credit, files: {work, blocked, done, idle} (paths with {id}),
bob (true: the zoo bobs it when done, for packs without a done animation), sprites: [{id,
name, w, h (display px), tile}]}. The packs come from render_cube_pets.py and
render_kenney.py.

Run: uv run scripts/make_packs.py   (the pack scripts run it themselves)
"""

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PACKS = REPO / "mods" / "zoo" / "packs"
ORDER = ["cube-pets", "blocky", "mini"]

def write_catalog():
    packs = {}
    for f in PACKS.glob("*.json"):
        p = json.loads(f.read_text(encoding="utf-8"))
        packs[p["id"]] = p
    ordered = [packs[k] for k in ORDER if k in packs] + [p for k, p in sorted(packs.items()) if k not in ORDER]
    body = json.dumps(ordered, ensure_ascii=False, separators=(",", ":"))
    text = ("// Generated by scripts/make_packs.py from mods/zoo/packs/*.json: the sprite packs, in\n"
            "// picker order. A sprite is \"<pack>/<id>\"; files[state] with {id} is its image.\n"
            f"export default {body};\n")
    for mod in ("zoo", "zoo-agents", "my-tabs"):
        (REPO / "mods" / mod / "sprites.js").write_text(text, encoding="utf-8", newline="\n")
    print("catalog:", ", ".join(f"{p['id']} ({len(p['sprites'])})" for p in ordered))


if __name__ == "__main__":
    write_catalog()
